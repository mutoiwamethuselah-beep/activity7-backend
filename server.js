/* ---------- Health check ---------- */

app.get("/health", async (req, res) => {
  try {
    await pool.query("SELECT 1");
    res.status(200).json({ status: "ok", database: "connected" });
  } catch (error) {
    console.error("Health check failed:", error.message);
    res.status(503).json({ status: "error", message: "Database is not reachable." });
  }
});

/* ---------- Record routes ---------- */

app.use("/api/records", require("./routes/records"));

/* ---------- Unknown routes and errors ---------- */

app.use((req, res) => {
  res.status(404).json({ message: "Route not found." });
});

// Four parameters: Express recognises this as the error handler.
// eslint-disable-next-line no-unused-vars
app.use((error, req, res, next) => {
  if (error.type === "entity.parse.failed" || error instanceof SyntaxError) {
    return res.status(400).json({ message: "Request body is not valid JSON." });
  }
  if (error.type === "entity.too.large") {
    return res.status(400).json({ message: "Request body is too large." });
  }
  console.error("Unexpected error:", error);
  res.status(500).json({ message: "Something went wrong on the server." });
});

/* ---------- Start ---------- */

async function ensureSchema() {
  try {
    const sql = fs.readFileSync(path.join(__dirname, "schema.sql"), "utf8");
    await pool.query(sql);
    console.log("Database schema is ready.");
  } catch (error) {
    // The server still starts so /health can report the problem.
    console.error("Could not prepare the database:", error.message);
  }
}

const port = process.env.PORT || 3000;
ensureSchema().then(() => {
  app.listen(port, "0.0.0.0", () => {
    console.log(`Server listening on port ${port}`);
  });
});
