// CLIENT_ORIGINS=http://localhost:5500,https://your-final-site.netlify.app
const origins = (process.env.CLIENT_ORIGINS || "")
  .split(",").map(value => value.trim()).filter(Boolean);

app.use(cors({ origin: origins }));
app.use(express.json());

